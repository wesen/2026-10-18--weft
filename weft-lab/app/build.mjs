// Builds Weft Lab into one artifact page: generated modules (examples with their headers, docs), an
// esbuild bundle (React comes from cdnjs as UMD globals) and the CSS, inlined. No wasm engine: the
// compiler and simulator are plain JavaScript in src/core.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from "node:fs";
import * as esbuild from "esbuild";

const here = (p) => new URL(p, import.meta.url);
const read = (p) => readFileSync(here(p), "utf8");
const dev = process.argv.includes("--dev");

// ---------- generated modules ----------
function parseHeader(text) {
  const head = text.match(/^\s*\/\*\*\s*([A-Z]-\d+)?\s*([^\n]*)\n([\s\S]*?)\*\//);
  const f = {};
  let cur = null;
  for (const raw of (head?.[3] || "").split("\n")) {
    const l = raw.replace(/^\s*\*\s?/, "");
    const m = l.match(/^\s*(group|about|shows|watch|try)\s{2,}(.*)$/);
    if (m) { cur = m[1]; f[cur] = m[2].trim(); } else if (cur && l.trim()) f[cur] += " " + l.trim();
  }
  return {
    id: head?.[1] || null, title: (head?.[2] || "Untitled").trim(), group: f.group || "Mine", about: f.about || "",
    shows: (f.shows || "").split("·").map((s) => s.trim()).filter(Boolean), watch: f.watch || "",
    tries: (f.try || "").split("|").map((s) => s.trim()).filter(Boolean),
  };
}
const files = readdirSync(here("../examples/")).filter((f) => /^F-\d+.*\.js$/.test(f)).sort();
const examples = files.map((file) => { const text = readFileSync(here("../examples/" + file), "utf8"); return { ...parseHeader(text), file, text }; });
writeFileSync(here("src/examples.gen.js"), "// generated by build.mjs from ../examples/*.js\nexport const EXAMPLES = " + JSON.stringify(examples) + ";\n");
writeFileSync(here("src/docs.gen.js"), `// generated by build.mjs\nexport const REFERENCE = ${JSON.stringify(read("src/ui/reference.txt"))};\nexport const GUIDELINES = ${JSON.stringify(read("src/agent/guidelines.txt"))};\n`);

// ---------- bundle ----------
const globals = {
  name: "umd-globals",
  setup(b) {
    b.onResolve({ filter: /^react(-dom)?(\/client)?$/ }, (a) => ({ path: a.path, namespace: "umd" }));
    b.onLoad({ filter: /.*/, namespace: "umd" }, (a) => ({ contents: `module.exports = ${a.path.startsWith("react-dom") ? "window.ReactDOM" : "window.React"};`, loader: "js" }));
  },
};
const out = await esbuild.build({
  entryPoints: [here("src/main.jsx").pathname], bundle: true, format: "iife", write: false, minify: !dev, target: "es2022",
  jsx: "transform", define: { "process.env.NODE_ENV": '"production"' }, plugins: [globals], legalComments: "none", logLevel: "warning",
  loader: { ".txt": "text" }, keepNames: true,
});
const js = out.outputFiles[0].text;

// ---------- page ----------
const css = read("src/ui/forge-base.css").replace(/^\s*<style>\s*/, "").replace(/\s*<\/style>\s*$/, "") + "\n" + read("src/ui/lab.css") + "\n" + read("src/ui/weft.css");
const esc = (s) => s.replace(/<\/script/gi, "<\\/script").replace(/<!--/g, "<\\!--");
const html = `<title>Weft Lab</title>
<meta name="claude:viewport-fit-sides" content="cover">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="An FPGA design lab: Weft scripts compiled to one DAG per clock domain, simulated cycle by cycle on a virtual board, with passes, a build report, waves, live changes, proofs and an architect agent.">
<style>
${css}
</style>
<div id="root"></div>
<script src="https://cdnjs.cloudflare.com/ajax/libs/react/18.3.1/umd/react.production.min.js"></script>
<script src="https://cdnjs.cloudflare.com/ajax/libs/react-dom/18.3.1/umd/react-dom.production.min.js"></script>
<script>
${esc(js)}
</script>
`;
mkdirSync(here("dist"), { recursive: true });
writeFileSync(here("dist/index.html"), html);
const kb = (n) => (n / 1024).toFixed(0) + " KB";
console.log(`dist/index.html ${kb(Buffer.byteLength(html))} (bundle ${kb(js.length)}, css ${kb(css.length)}, ${examples.length} examples)`);
