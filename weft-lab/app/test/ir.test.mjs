import { Graph } from "../src/core/ir.js";
import { u, s, bit, binType, join } from "../src/core/types.js";
import assert from "node:assert/strict";
const g = new Graph("sys", 100e6);
const en = g.input("counter.en", bit), dn = g.input("counter.down", bit);
const v = g.reg("counter.value", u(8));
const one = g.const(1);
const dec = g.add("sub", [v, one], binType("sub", u(8), u(1)), {}, { line: 18, src: "$.value - 1" });
const inc = g.add("add", [v, one], binType("add", u(8), u(1)), {}, { line: 18, src: "$.value + 1" });
const inc2 = g.add("add", [v, one], binType("add", u(8), u(1)));
assert.equal(inc, inc2, "hash-consing merges equal nodes");
const sel = g.add("mux", [dn, dec, inc], join(g.node(dec).type, g.node(inc).type));
const w = g.add("wrap", [sel], u(8));
const nx = g.add("mux", [en, w, v], u(8));
g.setNext(v, nx);
const z = g.add("eq", [v, g.const(0)], bit);
g.output("counter.zero", z);
assert.deepEqual(g.verify(), []);
assert.equal(g.users(v).length >= 3, true);
const h1 = g.hash(); g.node(v).attrs.init = 3; assert.notEqual(g.hash(), h1, "hash covers init");
console.log(g.print());
console.log(g.stats());
console.log("ir ok");
