package validate

import (
	"fmt"
	"math/big"
	"regexp"
	"strings"

	"github.com/pkg/errors"
)

// Testbench is a generated testbench and the change memories it reads ($readmemh, relative paths).
type Testbench struct {
	Verilog string
	Mems    map[string]string // file name → contents
}

var mismatchRE = regexp.MustCompile(`MISMATCH cycle=(\d+) port=(\S+) got=(\S+) want=(\S+)`)
var passRE = regexp.MustCompile(`WEFT-COSIM PASS (\d+)`)

// Generate writes the testbench for one scenario. Each cycle k it applies the inputs of k, checks every
// output against its value at k (the bits the design binds, or every bit of a checked domain-module port),
// then raises the clock for edge k. rst stays low: the simulator never resets, and registers start from their
// initializers on both sides.
func Generate(v *Vectors, s *ScenarioVectors) (*Testbench, error) {
	b := v.Bundle
	if len(b.Clocks) != 1 {
		return nil, errors.Errorf("%d clocks: co-simulation counts cycles of one clock", len(b.Clocks))
	}
	module, clkPort, ports := v.ports()
	byPort := make([][]Change, len(ports))
	for _, c := range s.Changes {
		byPort[c.Port] = append(byPort[c.Port], c)
	}
	tb := &Testbench{Mems: map[string]string{}}
	var decl, conns, apply, check strings.Builder
	conns.WriteString(fmt.Sprintf("    .%s(clk),\n    .%s(rst)", clkPort, b.Reset.Port))
	for i, p := range ports {
		w := p.width
		sig := "p_" + p.name
		if p.dir == "in" {
			fmt.Fprintf(&decl, "  reg  [%d:0] %s = 0;\n", w-1, sig)
		} else {
			fmt.Fprintf(&decl, "  wire [%d:0] %s;\n  reg  [%d:0] want_%s = 0;\n", w-1, sig, w-1, p.name)
		}
		fmt.Fprintf(&conns, ",\n    .%s(%s)", p.name, sig)
		n := len(byPort[i])
		if n > 0 {
			mem := p.name + ".mem"
			var text strings.Builder
			for _, c := range byPort[i] {
				v, ok := new(big.Int).SetString(c.Value, 16)
				if !ok {
					return nil, errors.Errorf("port %s: bad value %q at cycle %d", p.name, c.Value, c.Cycle)
				}
				word := new(big.Int).Lsh(big.NewInt(c.Cycle), uint(w))
				word.Or(word, v)
				fmt.Fprintf(&text, "%x\n", word)
			}
			tb.Mems[mem] = text.String()
			fmt.Fprintf(&decl, "  reg  [%d:0] ch_%s [0:%d];\n  integer i_%s = 0;\n  initial $readmemh(%q, ch_%s);\n", 63+w, p.name, n-1, p.name, mem, p.name)
			target := sig
			if p.dir != "in" {
				target = "want_" + p.name
			}
			fmt.Fprintf(&apply, "      while (i_%s < %d && ch_%s[i_%s][%d:%d] == cycle) begin %s = ch_%s[i_%s][%d:0]; i_%s = i_%s + 1; end\n",
				p.name, n, p.name, p.name, 63+w, w, target, p.name, p.name, w-1, p.name, p.name)
		}
		if p.mask != nil && p.mask.Sign() != 0 {
			mask := p.mask
			fmt.Fprintf(&check, "      if ((%s & %d'h%x) !== (want_%s & %d'h%x)) begin\n        $display(\"MISMATCH cycle=%%0d port=%s got=%%h want=%%h\", cycle, %s & %d'h%x, want_%s & %d'h%x);\n        $finish;\n      end\n",
				sig, w, mask, p.name, w, mask, p.name, sig, w, mask, p.name, w, mask)
		}
	}
	tb.Verilog = fmt.Sprintf(`// Generated by weft validate: co-simulation of %s, scenario %q (%d cycles).
// Each cycle: apply the inputs recorded for it, check the outputs, then the rising edge.
`+"`timescale 1ns/1ps"+`
module weft_tb;
  reg clk = 0;
  reg rst = 0;
  reg [63:0] cycle;
%s
  %s dut (
%s
  );

  initial begin
    for (cycle = 1; cycle <= %d; cycle = cycle + 1) begin
%s      #1;
%s      #4 clk = 1;
      #5 clk = 0;
    end
    $display("WEFT-COSIM PASS %%0d", %d);
    $finish;
  end
endmodule
`, b.Design, s.Name, s.Cycles, decl.String(), module, conns.String(), s.Cycles, apply.String(), check.String(), s.Cycles)
	return tb, nil
}

// Mismatch is the first difference a testbench found.
type Mismatch struct {
	Cycle int64  `json:"cycle"`
	Port  string `json:"port"`
	Got   string `json:"got"`
	Want  string `json:"want"`
}

// parseOutput reads a vvp run: the pass line, or the first mismatch.
func parseOutput(out string) (passed bool, cycles int64, mm *Mismatch) {
	if m := mismatchRE.FindStringSubmatch(out); m != nil {
		var c int64
		_, _ = fmt.Sscan(m[1], &c)
		return false, 0, &Mismatch{Cycle: c, Port: m[2], Got: m[3], Want: m[4]}
	}
	if m := passRE.FindStringSubmatch(out); m != nil {
		_, _ = fmt.Sscan(m[1], &cycles)
		return true, cycles, nil
	}
	return false, 0, nil
}
